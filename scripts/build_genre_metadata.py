#!/usr/bin/env python3
"""Generate the small static genre registry; never classify books automatically."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def main():
 taxonomy=json.loads((ROOT/'Resources/genre-taxonomy.json').read_text())
 (ROOT/'js/genre-metadata.js').write_text('// Generated by scripts/build_genre_metadata.py; no reading-data migration.\n'+ 'globalThis.BOKASAFN_GENRES = '+json.dumps(taxonomy,ensure_ascii=False,separators=(',',':'))+';\n')
if __name__=='__main__':main()
